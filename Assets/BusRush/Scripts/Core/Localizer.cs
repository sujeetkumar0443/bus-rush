using System;
using System.Collections.Generic;
using UnityEngine;

namespace BusRush
{
    /// <summary>The languages offered by Settings. Order = column order after "key" in the string table, and the order Settings cycles through.</summary>
    public enum Language
    {
        English = 0,
        Spanish = 1,
        Portuguese = 2,
        French = 3,
        Hindi = 4
    }

    /// <summary>
    /// One string table for every UI string. Keys are the English texts (templates use {0}, {1}); a missing key or an empty
    /// translation falls back to the key itself, so English needs no table. The table is Resources/Localization/strings.txt
    /// (tab separated: key, es, pt, fr, hi), generated by Tools/Localization/build_localization.py: the Hindi column is
    /// pre-shaped into private-use code points that the static "HindiClusters SDF" fallback font draws.
    /// The chosen language lives in PlayerPrefs, is applied at startup and <see cref="Changed"/> fires when it is set.
    /// </summary>
    public static class Localizer
    {
        public const string PrefsKey = "BusRush.Language";
        public const string NativeKey = "@native";

        private static readonly string[] Codes = { "en", "es", "pt", "fr", "hi" };

        private static Dictionary<string, string[]> table;
        private static Language current;
        private static bool ready;

        /// <summary>Raised after <see cref="Set"/> changed the language: every visible text must re-read its string.</summary>
        public static event Action Changed;

        public static Language Current
        {
            get
            {
                Ensure();
                return current;
            }
        }

        public static int Count => Codes.Length;

        public static string Code(Language language) => Codes[(int)language];

        /// <summary>The language name written in that language ("Español", Hindi pre-shaped...).</summary>
        public static string NativeName(Language language)
        {
            Ensure();
            if (language == Language.English) return "English";
            return table.TryGetValue(NativeKey, out string[] row) && !string.IsNullOrEmpty(row[(int)language - 1]) ? row[(int)language - 1] : language.ToString();
        }

        /// <summary>All keys of the table (for checks).</summary>
        public static IEnumerable<string> Keys
        {
            get
            {
                Ensure();
                return table.Keys;
            }
        }

        public static bool Has(string key)
        {
            Ensure();
            return table.ContainsKey(key);
        }

        /// <summary>The translation of <paramref name="language"/> for a key ("" when it has none); English is the key.</summary>
        public static string Get(string key, Language language)
        {
            Ensure();
            if (language == Language.English) return key;
            return table.TryGetValue(key, out string[] row) ? row[(int)language - 1] ?? string.Empty : string.Empty;
        }

        /// <summary>Saves and applies a language, then notifies every visible text.</summary>
        public static void Set(Language language)
        {
            Ensure();
            if (language == current) return;
            current = language;
            PlayerPrefs.SetInt(PrefsKey, (int)language);
            PlayerPrefs.Save();
            Changed?.Invoke();
        }

        public static Language Next(Language language) => (Language)(((int)language + 1) % Codes.Length);

        /// <summary>Translated text for an English key in the current language.</summary>
        public static string T(string key)
        {
            if (string.IsNullOrEmpty(key)) return key;
            Ensure();
            if (current == Language.English) return key;
            if (!table.TryGetValue(key, out string[] row)) return key;
            string v = row[(int)current - 1];
            return string.IsNullOrEmpty(v) ? key : v;
        }

        /// <summary>Translated template filled with the arguments (string.Format).</summary>
        public static string F(string key, params object[] args) => string.Format(T(key), args);

        // ------------------------------------------------------------------ loading

        private static void Ensure()
        {
            if (ready) return;
            table = new Dictionary<string, string[]>(256);
            var asset = Resources.Load<TextAsset>("Localization/strings");
            if (asset != null) Parse(asset.text);
            else Debug.LogWarning("[Localizer] Resources/Localization/strings.txt is missing: every text stays English.");
            int saved = PlayerPrefs.GetInt(PrefsKey, (int)Language.English);
            current = saved >= 0 && saved < Codes.Length ? (Language)saved : Language.English;
            ready = true;
        }

        private static void Parse(string text)
        {
            string[] lines = text.Split('\n');
            for (int i = 1; i < lines.Length; i++) // line 0 is the header
            {
                string line = lines[i].TrimEnd('\r');
                if (line.Length == 0) continue;
                string[] cols = line.Split('\t');
                if (cols.Length < 2) continue;
                var row = new string[Codes.Length - 1];
                for (int c = 0; c < row.Length; c++) row[c] = c + 1 < cols.Length ? cols[c + 1] : string.Empty;
                table[cols[0]] = row;
            }
        }

        /// <summary>For tests: forget everything, the next call reloads the table and the saved language (as a restart would).</summary>
        public static void ResetForTests()
        {
            ready = false;
            table = null;
        }

        [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.SubsystemRegistration)]
        private static void ResetStatics()
        {
            ready = false;
            table = null;
            Changed = null;
        }

        [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.BeforeSceneLoad)]
        private static void ApplyAtStartup() => Ensure();
    }
}
